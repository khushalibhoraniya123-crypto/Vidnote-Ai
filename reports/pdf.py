def generate_video_pdf_report(video_instance: Video, include_transcript: bool = True) -> io.BytesIO:
    """
    Generate an executive PDF report for the given Video model instance.
    Includes title, metadata, summaries, key points, timestamps, action items, and optional transcript.
    
    Returns:
        io.BytesIO buffer containing binary PDF data.
    """
    try:
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            leftMargin=54,
            rightMargin=54,
            topMargin=54,
            bottomMargin=54
        )

        styles = get_report_styles()
        story = []

        # =====================================================================
        # 1. HEADER & TITLE BANNER
        # =====================================================================
        story.append(Paragraph("VidNote AI", styles['DocTitle']))
        story.append(Paragraph("Executive Video Summary & Smart Intelligence Report", styles['DocSubtitle']))
        story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#2563eb"), spaceAfter=10))

        # Video Title & Description
        safe_title = escape(video_instance.title or "Untitled Video")
        story.append(Paragraph(safe_title, styles['VideoTitle']))

        if video_instance.description:
            safe_desc = escape(video_instance.description)
            story.append(Paragraph(safe_desc, styles['Body']))
            story.append(Spacer(1, 4))

        # =====================================================================
        # 2. METADATA TABLE
        # =====================================================================
        upload_date_str = video_instance.created_at.strftime("%b %d, %Y %H:%M") if video_instance.created_at else "N/A"
        duration_str = video_instance.formatted_duration or "00:00:00"
        size_str = video_instance.formatted_file_size or "0 KB"
        lang_str = (video_instance.language or "EN").upper()
        user_str = video_instance.user.username if video_instance.user else "Anonymous"

        meta_data = [
            [
                Paragraph("Uploaded By:", styles['MetaLabel']),
                Paragraph(user_str, styles['MetaValue']),
                Paragraph("Duration:", styles['MetaLabel']),
                Paragraph(duration_str, styles['MetaValue']),
            ],
            [
                Paragraph("Date:", styles['MetaLabel']),
                Paragraph(upload_date_str, styles['MetaValue']),
                Paragraph("File Size:", styles['MetaLabel']),
                Paragraph(size_str, styles['MetaValue']),
            ],
            [
                Paragraph("Language:", styles['MetaLabel']),
                Paragraph(lang_str, styles['MetaValue']),
                Paragraph("Status:", styles['MetaLabel']),
                Paragraph(video_instance.get_status_display(), styles['MetaValue']),
            ]
        ]

        meta_table = Table(meta_data, colWidths=[80, 160, 70, 194])
        meta_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
            ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
            ('LEFTPADDING', (0, 0), (-1, -1), 6),
            ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ]))
        story.append(meta_table)
        story.append(Spacer(1, 12))

        # =====================================================================
        # 3. EXECUTIVE SUMMARY (TL;DR)
        # =====================================================================
        summary_obj = getattr(video_instance, 'summary', None)
        if summary_obj and summary_obj.short_summary:
            story.append(Paragraph("1. Executive Summary (TL;DR)", styles['SectionHeading']))
            safe_short = escape(summary_obj.short_summary)
            exec_table = Table(
                [[Paragraph(safe_short, styles['ExecutiveSummary'])]],
                colWidths=[504]
            )
            exec_table.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#eff6ff")),
                ('BOX', (0, 0), (-1, -1), 1, colors.HexColor("#93c5fd")),
                ('TOPPADDING', (0, 0), (-1, -1), 8),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 8),
                ('LEFTPADDING', (0, 0), (-1, -1), 10),
                ('RIGHTPADDING', (0, 0), (-1, -1), 10),
            ]))
            story.append(exec_table)
            story.append(Spacer(1, 10))

        # =====================================================================
        # 4. KEY LEARNING POINTS
        # =====================================================================
        if summary_obj and summary_obj.key_points:
            story.append(Paragraph("2. Key Learning Points & Takeaways", styles['SectionHeading']))
            for pt in summary_obj.key_points:
                safe_pt = escape(str(pt))
                bullet_item = f"<b>&bull;</b>  {safe_pt}"
                story.append(Paragraph(bullet_item, styles['KeyPointItem']))
            story.append(Spacer(1, 10))

        # =====================================================================
        # 5. DETAILED STUDY NOTES & BREAKDOWN
        # =====================================================================
        if summary_obj and summary_obj.detailed_summary:
            story.append(Paragraph("3. Detailed Lecture Breakdown & Notes", styles['SectionHeading']))
            paragraphs = summary_obj.detailed_summary.split('\n')
            for p in paragraphs:
                p_clean = p.strip()
                if p_clean:
                    story.append(Paragraph(escape(p_clean), styles['Body']))
            story.append(Spacer(1, 10))

        # =====================================================================
        # 6. IMPORTANT TIMESTAMPS & KEY MOMENTS
        # =====================================================================
        moments = list(video_instance.important_moments.all().order_by('start_time'))
        if moments:
            story.append(Paragraph("4. Key Moments & Indexed Timestamps", styles['SectionHeading']))
            moments_rows = [
                [
                    Paragraph("Timestamp", styles['TableHeader']),
                    Paragraph("Topic / Key Moment", styles['TableHeader']),
                    Paragraph("Priority", styles['TableHeader']),
                    Paragraph("Description", styles['TableHeader'])
                ]
            ]

            for m in moments:
                time_range = m.formatted_time_range
                title_txt = escape(m.title)
                prio_txt = m.get_importance_display()
                desc_txt = escape(m.description or "—")

                moments_rows.append([
                    Paragraph(time_range, styles['TableCellBold']),
                    Paragraph(title_txt, styles['TableCellBold']),
                    Paragraph(prio_txt, styles['TableCell']),
                    Paragraph(desc_txt, styles['TableCell'])
                ])

            moments_table = Table(moments_rows, colWidths=[95, 145, 60, 204], repeatRows=1)
            moments_table.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#1e40af")),
                ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
                ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor("#f8fafc")]),
                ('TOPPADDING', (0, 0), (-1, -1), 4),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
                ('LEFTPADDING', (0, 0), (-1, -1), 5),
                ('RIGHTPADDING', (0, 0), (-1, -1), 5),
            ]))
            story.append(moments_table)
            story.append(Spacer(1, 10))

        # =====================================================================
        # 7. ACTION ITEMS & DELIVERABLES
        # =====================================================================
        action_items = list(video_instance.action_items.all().order_by('status', 'priority', 'timestamp'))
        if action_items:
            story.append(Paragraph("5. Action Items & Deliverables", styles['SectionHeading']))
            ai_rows = [
                [
                    Paragraph("Status", styles['TableHeader']),
                    Paragraph("Actionable Task", styles['TableHeader']),
                    Paragraph("Priority", styles['TableHeader']),
                    Paragraph("Spoken Time", styles['TableHeader']),
                    Paragraph("Context / Details", styles['TableHeader'])
                ]
            ]

            for item in action_items:
                status_icon = "[DONE]" if item.is_completed else "[TODO]"
                task_txt = escape(item.task)
                prio_txt = item.get_priority_display()
                ts_txt = item.formatted_timestamp if item.timestamp is not None else "—"
                desc_txt = escape(item.description or "—")

                ai_rows.append([
                    Paragraph(status_icon, styles['TableCellBold']),
                    Paragraph(task_txt, styles['TableCellBold']),
                    Paragraph(prio_txt, styles['TableCell']),
                    Paragraph(ts_txt, styles['TableCell']),
                    Paragraph(desc_txt, styles['TableCell'])
                ])

            ai_table = Table(ai_rows, colWidths=[55, 145, 55, 65, 184], repeatRows=1)
            ai_table.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#0f766e")),
                ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
                ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor("#f0fdfa")]),
                ('TOPPADDING', (0, 0), (-1, -1), 4),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
                ('LEFTPADDING', (0, 0), (-1, -1), 5),
                ('RIGHTPADDING', (0, 0), (-1, -1), 5),
            ]))
            story.append(ai_table)
            story.append(Spacer(1, 10))

        # =====================================================================
        # 8. OPTIONAL TIMESTAMPED TRANSCRIPT
        # =====================================================================
        segments = list(video_instance.transcript_segments.all().order_by('segment_order', 'start_time'))
        if include_transcript and segments:
            story.append(Paragraph("6. Full Timestamped Speech Transcript", styles['SectionHeading']))
            transcript_rows = [
                [
                    Paragraph("Time Interval", styles['TableHeader']),
                    Paragraph("Spoken Speech Text", styles['TableHeader'])
                ]
            ]

            for seg in segments:
                t_range = f"{seg.formatted_start_time} - {seg.formatted_end_time}"
                t_text = escape(seg.text)

                transcript_rows.append([
                    Paragraph(t_range, styles['TranscriptTime']),
                    Paragraph(t_text, styles['TranscriptText'])
                ])

            transcript_table = Table(transcript_rows, colWidths=[105, 399], repeatRows=1)
            transcript_table.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#334155")),
                ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
                ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor("#f8fafc")]),
                ('TOPPADDING', (0, 0), (-1, -1), 3),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
                ('LEFTPADDING', (0, 0), (-1, -1), 5),
                ('RIGHTPADDING', (0, 0), (-1, -1), 5),
            ]))
            story.append(transcript_table)

        # Build document with NumberedCanvas
        doc.build(story, canvasmaker=NumberedCanvas)
        buffer.seek(0)
        return buffer

    except Exception as e:
        logger.error(f"PDF report generation failed for video {video_instance.pk}: {str(e)}", exc_info=True)
        raise PDFGenerationError(f"Failed to generate PDF report: {str(e)}")
